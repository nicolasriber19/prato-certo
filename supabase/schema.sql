-- Prato Certo: tabelas, regras de acesso (RLS) e políticas.
--
-- Como usar: painel do Supabase → SQL Editor → New query → colar este arquivo → Run.
-- Pode rodar de novo sem perder dados: só cria o que falta e refaz as políticas.
-- Depois rode o supabase/seed.sql, e então "npm run conferir".
--
-- Valores usados nas listas (text[]), iguais aos do JavaScript:
--   restrições / tags:  vegano, vegetariano, sem_gluten, sem_lactose
--   momentos:           almoco_rapido, jantar_romantico, lanche_economico
--   cozinhas:           brasileira, nordestina, italiana, japonesa, arabe,
--                       mexicana, indiana, hamburguer, saudavel, cafeteria


-- 1. Catálogo: restaurantes e pratos (de exemplo nesta versão) -----------------

create table if not exists public.restaurantes (
  id          bigint generated by default as identity primary key,
  nome        text not null,
  bairro      text not null,
  endereco    text not null,
  latitude    double precision not null,
  longitude   double precision not null,
  faixa_preco smallint not null check (faixa_preco between 1 and 4), -- 1 = barato, 4 = caro
  cozinhas    text[] not null default '{}',
  descricao   text not null default ''
);

create table if not exists public.pratos (
  id                bigint generated by default as identity primary key,
  restaurante_id    bigint not null references public.restaurantes (id) on delete cascade,
  nome              text not null,
  descricao         text not null default '',
  preco             numeric(8, 2) not null check (preco > 0),
  cozinha           text not null,
  tags              text[] not null default '{}', -- restrições que o prato atende
  momentos          text[] not null default '{}',
  tempo_preparo_min smallint not null default 20,
  foto              text,                          -- caminho em public/img/pratos/; vazio = imagem provisória
  texto_alternativo text not null default ''       -- vazio = o site usa o nome do prato
);

create index if not exists pratos_restaurante_idx on public.pratos (restaurante_id);


-- 2. Dados de cada pessoa ----------------------------------------------------
-- "usuario_id" já vem preenchido com quem está logado (auth.uid()).
-- Apagar a conta em Authentication → Users apaga também estas linhas (on delete cascade).

create table if not exists public.perfis (
  id            uuid primary key references auth.users (id) on delete cascade,
  nome          text not null default '',
  gostos        text[] not null default '{}', -- cozinhas de que gosta
  nao_gosta     text[] not null default '{}', -- cozinhas que quer evitar
  restricoes    text[] not null default '{}',
  orcamento_max numeric(8, 2),                -- por prato; vazio = sem limite
  bairro        text not null default '',
  atualizado_em timestamptz not null default now()
);

create table if not exists public.favoritos (
  id             bigint generated by default as identity primary key,
  usuario_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  prato_id       bigint references public.pratos (id) on delete cascade,
  restaurante_id bigint references public.restaurantes (id) on delete cascade,
  criado_em      timestamptz not null default now(),
  -- Cada favorito é um prato OU um restaurante, nunca os dois.
  check (num_nonnulls(prato_id, restaurante_id) = 1)
);

create unique index if not exists favoritos_prato_unico
  on public.favoritos (usuario_id, prato_id) where prato_id is not null;
create unique index if not exists favoritos_restaurante_unico
  on public.favoritos (usuario_id, restaurante_id) where restaurante_id is not null;

create table if not exists public.escolhas (
  id         bigint generated by default as identity primary key,
  usuario_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  prato_id   bigint not null references public.pratos (id) on delete cascade,
  momento    text not null check (momento in ('almoco_rapido', 'jantar_romantico', 'lanche_economico')),
  criado_em  timestamptz not null default now()
);

create index if not exists escolhas_usuario_idx on public.escolhas (usuario_id, criado_em desc);

create table if not exists public.avaliacoes (
  id            bigint generated by default as identity primary key,
  usuario_id    uuid not null default auth.uid() references auth.users (id) on delete cascade,
  prato_id      bigint not null references public.pratos (id) on delete cascade,
  nota          smallint not null check (nota between 1 and 5),
  comentario    text not null default '' check (char_length(comentario) <= 500),
  atualizado_em timestamptz not null default now(),
  unique (usuario_id, prato_id) -- uma avaliação por pessoa e prato; avaliar de novo substitui
);


-- 3. Regras de acesso (RLS) ---------------------------------------------------
-- Com a RLS ligada, ninguém lê nem grava nada, a não ser o que uma política permite.

alter table public.restaurantes enable row level security;
alter table public.pratos       enable row level security;
alter table public.perfis       enable row level security;
alter table public.favoritos    enable row level security;
alter table public.escolhas     enable row level security;
alter table public.avaliacoes   enable row level security;

-- Catálogo: qualquer pessoa lê. Ninguém grava pelo site, só aqui pelo SQL Editor.
drop policy if exists "Catálogo: leitura pública" on public.restaurantes;
create policy "Catálogo: leitura pública" on public.restaurantes
  for select to anon, authenticated using (true);

drop policy if exists "Catálogo: leitura pública" on public.pratos;
create policy "Catálogo: leitura pública" on public.pratos
  for select to anon, authenticated using (true);

-- Dados pessoais: cada pessoa lê, cria, muda e apaga só as próprias linhas.
-- "(select auth.uid())" é calculado uma vez por consulta, não uma vez por linha.
drop policy if exists "Perfil: só o próprio" on public.perfis;
create policy "Perfil: só o próprio" on public.perfis
  for all to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

drop policy if exists "Favoritos: só os próprios" on public.favoritos;
create policy "Favoritos: só os próprios" on public.favoritos
  for all to authenticated
  using ((select auth.uid()) = usuario_id)
  with check ((select auth.uid()) = usuario_id);

drop policy if exists "Escolhas: só as próprias" on public.escolhas;
create policy "Escolhas: só as próprias" on public.escolhas
  for all to authenticated
  using ((select auth.uid()) = usuario_id)
  with check ((select auth.uid()) = usuario_id);

drop policy if exists "Avaliações: só as próprias" on public.avaliacoes;
create policy "Avaliações: só as próprias" on public.avaliacoes
  for all to authenticated
  using ((select auth.uid()) = usuario_id)
  with check ((select auth.uid()) = usuario_id);

-- Permissões das tabelas para o site. A RLS acima continua filtrando as linhas.
grant select on public.restaurantes, public.pratos to anon, authenticated;
grant select, insert, update, delete
  on public.perfis, public.favoritos, public.escolhas, public.avaliacoes
  to authenticated;


-- 4. Média das notas ----------------------------------------------------------
-- Cada pessoa só lê as próprias avaliações (política acima). Esta função devolve
-- só a média e a quantidade de notas de cada prato: sem nomes, sem comentários.
-- Uso no site: supabase.rpc('notas_dos_pratos')

create or replace function public.notas_dos_pratos()
returns table (prato_id bigint, media numeric, total bigint)
language sql
stable
security definer
set search_path = ''
as $$
  select a.prato_id, round(avg(a.nota), 1), count(*)
  from public.avaliacoes as a
  group by a.prato_id
$$;

revoke execute on function public.notas_dos_pratos() from public;
grant execute on function public.notas_dos_pratos() to anon, authenticated;
